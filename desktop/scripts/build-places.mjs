// Writes src/core/detection/vocabulary/places.json from two MIT-licensed datasets of
// Vietnam's administrative units (decision 0161): the 34 provinces and cities since July
// 2025 (thanglequoc/vietnamese-provinces-database) and the 63 before (the legacy parser
// of tranngocminhhieu/vietnamadminunits). Countries are a short curated list.
//
//   mise exec -- node scripts/build-places.mjs            # fetches both files
//   mise exec -- node scripts/build-places.mjs <folder>   # reads them from a folder
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const sources = {
  current: {
    url: "https://raw.githubusercontent.com/thanglequoc/vietnamese-provinces-database/master/json/vn_only_simplified_json_generated_data_vn_units.json",
    file: "provinces-34.json",
    license: "MIT, github.com/thanglequoc/vietnamese-provinces-database",
  },
  former: {
    url: "https://raw.githubusercontent.com/tranngocminhhieu/vietnamadminunits/main/vietnamadminunits/data/parser_legacy.json",
    file: "parser_legacy.json",
    license: "MIT, github.com/tranngocminhhieu/vietnamadminunits",
  },
};
const folder = process.argv[2];
// The legacy file was written by Python and holds NaN, which is not JSON.
const parse = (text) => JSON.parse(text.replace(/\bNaN\b/g, "null"));
async function load(source) {
  if (folder) return parse(readFileSync(join(folder, source.file), "utf8"));
  const response = await fetch(source.url);
  if (!response.ok) throw new Error(`${source.url}: ${response.status}`);
  return parse(await response.text());
}
const current = await load(sources.current);
const legacy = await load(sources.former);
const shortName = (full) => full.replace(/^(?:Thành phố|Tỉnh)\s+/u, "");
const kind = (full) => (full.startsWith("Thành phố") ? "thành phố" : "tỉnh");
const provinces = current
  .map((unit) => ({ name: shortName(unit.FullName), kind: kind(unit.FullName), code: unit.Code }))
  .sort((a, b) => a.name.localeCompare(b.name, "vi"));
const currentNames = new Set(provinces.map((p) => p.name));
const former = Object.values(legacy.DICT_PROVINCE)
  .map((unit) => ({ name: unit.provinceShort, kind: kind(unit.province) }))
  .filter((p) => !currentNames.has(p.name))
  .sort((a, b) => a.name.localeCompare(b.name, "vi"));
const places = {
  $comment:
    "Generated by scripts/build-places.mjs; do not edit by hand. Provinces: the 34 since Resolution 202/2025/QH15 (1 July 2025) and the names before, from two MIT datasets; countries curated (decision 0155).",
  sources: Object.fromEntries(
    Object.entries(sources).map(([key, source]) => [
      key,
      { url: source.url, license: source.license },
    ]),
  ),
  generated: new Date().toISOString().slice(0, 10),
  provinces,
  formerProvinces: former,
  provinceAliases: ["hcm", "tphcm", "sài gòn", "saigon", "thừa thiên huế"],
  countries: [
    "việt nam",
    "úc",
    "mỹ",
    "hoa kỳ",
    "anh",
    "pháp",
    "đức",
    "ý",
    "nga",
    "nhật",
    "nhật bản",
    "hàn quốc",
    "trung quốc",
    "đài loan",
    "hồng kông",
    "thái lan",
    "lào",
    "campuchia",
    "singapore",
    "malaysia",
    "indonesia",
    "philippines",
    "ấn độ",
    "canada",
    "new zealand",
    "tây ban nha",
    "hà lan",
    "thụy sĩ",
    "châu âu",
    "châu á",
    "châu mỹ",
    "châu phi",
    "châu úc",
  ],
};
const out = fileURLToPath(new URL("../src/core/detection/vocabulary/places.json", import.meta.url));
writeFileSync(out, JSON.stringify(places, null, 2) + "\n");
console.log(`${provinces.length} provinces, ${former.length} former names -> ${out}`);
