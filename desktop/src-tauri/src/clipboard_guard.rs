//! The user's clipboard, borrowed for as short a time as possible (decision 0130).
//! Where a quick action cannot read or replace a selection through Accessibility, it
//! copies or pastes with the system chords, and those go through the clipboard. Around
//! each one the whole clipboard is saved, every item in every format (images, files,
//! rich text), and put back afterwards, unless someone else wrote to it in between.
//! What OfflineMask itself writes is marked so clipboard managers skip it and, on
//! macOS, kept off Universal Clipboard; on Windows, out of the clipboard history and
//! the cloud clipboard.
use tauri::{AppHandle, Runtime};

/// Identifies one state of the clipboard: it changes with every write by anyone.
pub type Stamp = u64;

#[derive(Default)]
pub struct Saved(imp::Saved);

/// Everything on the clipboard now, to be put back with [`restore`].
pub fn save<R: Runtime>(app: &AppHandle<R>) -> Saved {
    Saved(imp::save(app))
}
/// The clipboard's current state.
pub fn stamp<R: Runtime>(app: &AppHandle<R>) -> Stamp {
    imp::stamp(app)
}
/// Put `text` on the clipboard, marked as OfflineMask's own and short-lived; returns the
/// state it leaves, for [`restore`].
pub fn write_private<R: Runtime>(app: &AppHandle<R>, text: &str) -> Result<Stamp, String> {
    imp::write_private(app, text)
}
pub fn read_text<R: Runtime>(app: &AppHandle<R>) -> Option<String> {
    imp::read_text(app)
}
/// Put the saved clipboard back, but only while it is still in the state `left`: a copy
/// the user made in the meantime is theirs to keep.
pub fn restore<R: Runtime>(app: &AppHandle<R>, saved: Saved, left: Stamp) {
    if imp::stamp(app) == left {
        imp::restore(app, saved.0);
    }
}

#[cfg(target_os = "macos")]
mod imp {
    use objc2::rc::Retained;
    use objc2::runtime::ProtocolObject;
    use objc2_app_kit::{
        NSPasteboard, NSPasteboardContentsOptions, NSPasteboardItem, NSPasteboardTypeString,
        NSPasteboardWriting,
    };
    use objc2_foundation::{NSArray, NSData, NSString};
    use tauri::{AppHandle, Runtime};

    use super::Stamp;

    /// Each item as its types and their bytes.
    pub type Saved = Vec<Vec<(String, Vec<u8>)>>;

    /// The nspasteboard.org markers: transient (do not record), concealed (do not show),
    /// auto-generated (not the user's own copy).
    const MARKERS: [&str; 3] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
    ];

    fn board() -> Retained<NSPasteboard> {
        NSPasteboard::generalPasteboard()
    }
    pub fn stamp<R: Runtime>(_app: &AppHandle<R>) -> Stamp {
        board().changeCount() as Stamp
    }
    pub fn save<R: Runtime>(_app: &AppHandle<R>) -> Saved {
        let Some(items) = board().pasteboardItems() else {
            return Vec::new();
        };
        items
            .iter()
            .map(|item| {
                item.types()
                    .iter()
                    .filter_map(|kind| Some((kind.to_string(), item.dataForType(&kind)?.to_vec())))
                    .collect()
            })
            .collect()
    }
    fn write(items: &[Retained<NSPasteboardItem>], host_only: bool) {
        let board = board();
        if host_only {
            board.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
        } else {
            board.clearContents();
        }
        if items.is_empty() {
            return;
        }
        let objects: Vec<&ProtocolObject<dyn NSPasteboardWriting>> = items
            .iter()
            .map(|item| ProtocolObject::from_ref(&**item))
            .collect();
        board.writeObjects(&NSArray::from_slice(&objects));
    }
    pub fn restore<R: Runtime>(_app: &AppHandle<R>, saved: Saved) {
        let items: Vec<Retained<NSPasteboardItem>> = saved
            .iter()
            .map(|types| {
                let item = NSPasteboardItem::new();
                for (kind, bytes) in types {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind));
                }
                item
            })
            .collect();
        write(&items, false);
    }
    pub fn write_private<R: Runtime>(app: &AppHandle<R>, text: &str) -> Result<Stamp, String> {
        let item = NSPasteboardItem::new();
        // SAFETY: an AppKit constant, valid for the life of the process.
        let string_type = unsafe { NSPasteboardTypeString };
        if !item.setString_forType(&NSString::from_str(text), string_type) {
            return Err("io: clipboard".into());
        }
        for marker in MARKERS {
            item.setData_forType(&NSData::new(), &NSString::from_str(marker));
        }
        write(&[item], true);
        Ok(stamp(app))
    }
    pub fn read_text<R: Runtime>(_app: &AppHandle<R>) -> Option<String> {
        // SAFETY: an AppKit constant, valid for the life of the process.
        let string_type = unsafe { NSPasteboardTypeString };
        board()
            .stringForType(string_type)
            .map(|text| text.to_string())
    }
}

#[cfg(windows)]
mod imp {
    use std::ffi::c_void;
    use std::thread::sleep;
    use std::time::Duration;

    use tauri::{AppHandle, Manager, Runtime};
    use windows::core::w;
    use windows::Win32::Foundation::{GlobalFree, HANDLE, HGLOBAL, HWND};
    use windows::Win32::System::DataExchange::{
        CloseClipboard, EmptyClipboard, EnumClipboardFormats, GetClipboardData,
        GetClipboardSequenceNumber, OpenClipboard, RegisterClipboardFormatW, SetClipboardData,
    };
    use windows::Win32::System::Memory::{
        GlobalAlloc, GlobalLock, GlobalSize, GlobalUnlock, GMEM_MOVEABLE,
    };
    use windows::Win32::System::Ole::CF_UNICODETEXT;

    use super::Stamp;

    /// Each format and its bytes.
    pub type Saved = Vec<(u32, Vec<u8>)>;

    /// GDI handle formats are not memory blocks; Windows synthesizes them again from
    /// CF_DIB and the other memory formats that are saved.
    const GDI_FORMATS: [u32; 8] = [2, 3, 9, 14, 0x80, 0x82, 0x83, 0x8E];

    /// Ownership needs a window: with none, `SetClipboardData` fails after
    /// `EmptyClipboard`.
    fn owner<R: Runtime>(app: &AppHandle<R>) -> Option<HWND> {
        let window = app.get_webview_window("main")?;
        Some(HWND(window.hwnd().ok()?.0 as *mut c_void))
    }
    /// Another application may hold the clipboard open for a moment.
    struct Open;
    impl Open {
        fn new(owner: Option<HWND>) -> Option<Self> {
            for _ in 0..20 {
                // SAFETY: plain call; closed again by Drop.
                if unsafe { OpenClipboard(owner) }.is_ok() {
                    return Some(Open);
                }
                sleep(Duration::from_millis(10));
            }
            None
        }
    }
    impl Drop for Open {
        fn drop(&mut self) {
            // SAFETY: opened by `Open::new`.
            let _ = unsafe { CloseClipboard() };
        }
    }
    unsafe fn bytes_of(handle: HANDLE) -> Option<Vec<u8>> {
        let global = HGLOBAL(handle.0);
        let size = GlobalSize(global);
        let pointer = GlobalLock(global) as *const u8;
        if pointer.is_null() {
            return None;
        }
        let bytes = std::slice::from_raw_parts(pointer, size).to_vec();
        let _ = GlobalUnlock(global);
        Some(bytes)
    }
    /// Hand a copy of `bytes` to the clipboard, which then owns it.
    unsafe fn set(format: u32, bytes: &[u8]) {
        let Ok(global) = GlobalAlloc(GMEM_MOVEABLE, bytes.len().max(1)) else {
            return;
        };
        let pointer = GlobalLock(global) as *mut u8;
        if pointer.is_null() {
            let _ = GlobalFree(Some(global));
            return;
        }
        std::ptr::copy_nonoverlapping(bytes.as_ptr(), pointer, bytes.len());
        let _ = GlobalUnlock(global);
        if SetClipboardData(format, Some(HANDLE(global.0))).is_err() {
            let _ = GlobalFree(Some(global));
        }
    }
    pub fn stamp<R: Runtime>(_app: &AppHandle<R>) -> Stamp {
        // SAFETY: plain query.
        unsafe { GetClipboardSequenceNumber() as Stamp }
    }
    pub fn save<R: Runtime>(app: &AppHandle<R>) -> Saved {
        let Some(_open) = Open::new(owner(app)) else {
            return Vec::new();
        };
        let mut saved = Vec::new();
        let mut format = 0;
        loop {
            // SAFETY: the clipboard is open; formats are enumerated in order.
            format = unsafe { EnumClipboardFormats(format) };
            if format == 0 {
                break;
            }
            if GDI_FORMATS.contains(&format) {
                continue;
            }
            // SAFETY: the clipboard is open; the handle is read, not kept.
            if let Some(bytes) = unsafe { GetClipboardData(format).ok().and_then(|h| bytes_of(h)) }
            {
                saved.push((format, bytes));
            }
        }
        saved
    }
    pub fn restore<R: Runtime>(app: &AppHandle<R>, saved: Saved) {
        let Some(_open) = Open::new(owner(app)) else {
            return;
        };
        // SAFETY: the clipboard is open and owned by our window.
        unsafe {
            let _ = EmptyClipboard();
            for (format, bytes) in &saved {
                set(*format, bytes);
            }
        }
    }
    pub fn write_private<R: Runtime>(app: &AppHandle<R>, text: &str) -> Result<Stamp, String> {
        let wide: Vec<u8> = text
            .encode_utf16()
            .chain(std::iter::once(0))
            .flat_map(u16::to_le_bytes)
            .collect();
        {
            let _open = Open::new(owner(app)).ok_or("io: clipboard busy")?;
            // SAFETY: the clipboard is open and owned by our window.
            unsafe {
                EmptyClipboard().map_err(|_| "io: clipboard")?;
                set(CF_UNICODETEXT.0 as u32, &wide);
                // Kept out of clipboard monitors, the Win+V history and the cloud clipboard.
                let zero = 0u32.to_le_bytes();
                set(
                    RegisterClipboardFormatW(w!("ExcludeClipboardContentFromMonitorProcessing")),
                    &zero,
                );
                set(
                    RegisterClipboardFormatW(w!("CanIncludeInClipboardHistory")),
                    &zero,
                );
                set(
                    RegisterClipboardFormatW(w!("CanUploadToCloudClipboard")),
                    &zero,
                );
            }
        }
        Ok(stamp(app))
    }
    pub fn read_text<R: Runtime>(app: &AppHandle<R>) -> Option<String> {
        let _open = Open::new(owner(app))?;
        // SAFETY: the clipboard is open; the handle is read, not kept.
        let bytes = unsafe { bytes_of(GetClipboardData(CF_UNICODETEXT.0 as u32).ok()?)? };
        let units: Vec<u16> = bytes
            .chunks_exact(2)
            .map(|pair| u16::from_le_bytes([pair[0], pair[1]]))
            .take_while(|unit| *unit != 0)
            .collect();
        String::from_utf16(&units).ok()
    }
}

/// Elsewhere (Linux) only text can be saved; the state is the text itself.
#[cfg(not(any(target_os = "macos", windows)))]
mod imp {
    use std::hash::{Hash, Hasher};

    use tauri::{AppHandle, Runtime};
    use tauri_plugin_clipboard_manager::ClipboardExt;

    use super::Stamp;

    pub type Saved = Option<String>;

    fn hash(text: &Option<String>) -> Stamp {
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        text.hash(&mut hasher);
        hasher.finish()
    }
    pub fn read_text<R: Runtime>(app: &AppHandle<R>) -> Option<String> {
        app.clipboard().read_text().ok()
    }
    pub fn stamp<R: Runtime>(app: &AppHandle<R>) -> Stamp {
        hash(&read_text(app))
    }
    pub fn save<R: Runtime>(app: &AppHandle<R>) -> Saved {
        read_text(app)
    }
    pub fn restore<R: Runtime>(app: &AppHandle<R>, saved: Saved) {
        let _ = app.clipboard().write_text(saved.unwrap_or_default());
    }
    pub fn write_private<R: Runtime>(app: &AppHandle<R>, text: &str) -> Result<Stamp, String> {
        app.clipboard()
            .write_text(text.to_owned())
            .map_err(|_| "io: clipboard".to_string())?;
        Ok(stamp(app))
    }
}
